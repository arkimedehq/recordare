"""System C — Memobase (user profile + event timeline).

Requires: `python embed_server.py` (local embeddings) and `docker compose -f memobase/docker-compose.yml up -d`
with config generated by `setup_memobase.py`. LLM work happens server-side (DeepSeek).
One ChatBlob per session, messages stamped with the session timestamp. Blobs accumulate in the
user buffer (Memobase processes it when it exceeds its token threshold) and a final flush per user
processes the remainder — per-session flushes would skip short sessions (< 256 tokens).
"""
from __future__ import annotations

import uuid

from memobase import ChatBlob, MemoBaseClient

from evalkit.common import USAGE

URL = "http://localhost:8019"
TOKEN = "memeval"
NS = uuid.UUID("6f1c1f3e-2a7d-4c55-9a1e-7d3c2b9e0a11")


class MemobaseSystem:
    name = "memobase"

    def __init__(self) -> None:
        self.client = MemoBaseClient(project_url=URL, api_key=TOKEN)
        assert self.client.ping(), "Memobase server not reachable on :8019"
        self.users = {}

    def _user(self, name: str):
        if name not in self.users:
            uid = str(uuid.uuid5(NS, name))
            try:
                self.client.delete_user(uid)  # fresh state per run
            except Exception:  # noqa: BLE001 - user did not exist
                pass
            self.client.add_user(id=uid)
            self.users[name] = self.client.get_user(uid)
        return self.users[name]

    def ingest(self, sessions: list[dict]) -> None:
        before = self._usage_tokens()
        for s in sessions:
            u = self._user(s["user"])
            u.insert(ChatBlob(messages=[
                {"role": m["role"], "content": m["content"], "created_at": s["ts"]} for m in s["messages"]
            ]), sync=True)
            print(f"  ingested {s['id']}", flush=True)
        for u in self.users.values():
            u.flush(sync=True)
        after = self._usage_tokens()
        if before is not None and after is not None:
            USAGE.prompt["ingest"] = after[0] - before[0]
            USAGE.completion["ingest"] = after[1] - before[1]

    def _usage_tokens(self):
        """(input, output) tokens consumed server-side, if the server reports them."""
        try:
            usage = self.client.get_usage()
            return (int(usage.get("total_input_tokens", 0) or usage.get("input_tokens", 0)),
                    int(usage.get("total_output_tokens", 0) or usage.get("output_tokens", 0)))
        except Exception:  # noqa: BLE001
            return None

    def context(self, user: str, question: dict) -> str:
        u = self._user(user)
        return u.context(max_token_size=1200, chats=[{"role": "user", "content": question["q"]}])
